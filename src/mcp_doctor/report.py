"""Render a Report as Markdown, JSON or a rich terminal view."""

from __future__ import annotations

import json
from collections import Counter

from mcp_doctor.models import Issue, Report, Severity

SEV_ORDER = {Severity.ERROR: 0, Severity.WARNING: 1, Severity.INFO: 2}
SEV_ICON = {Severity.ERROR: "❌", Severity.WARNING: "⚠️", Severity.INFO: "ℹ️"}
SEV_STYLE = {Severity.ERROR: "bold red", Severity.WARNING: "yellow", Severity.INFO: "cyan"}
GRADE_STYLE = {"A": "bold green", "B": "green", "C": "yellow", "D": "dark_orange", "F": "bold red"}
FUZZ_BAD = {"accepted", "leaked", "crashed", "timeout"}


def sorted_issues(issues: list[Issue]) -> list[Issue]:
    return sorted(issues, key=lambda i: (SEV_ORDER[i.severity], i.rule))


def top_rules(report: Report, n: int = 3) -> list[tuple[str, int]]:
    return Counter(i.rule for i in report.all_issues).most_common(n)


def to_json(report: Report) -> str:
    return json.dumps(report.to_dict(), indent=2, ensure_ascii=False)


def _md_escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def to_markdown(report: Report) -> str:
    c = report.counts()
    lines = [
        f"# MCP Doctor report: `{report.server}`",
        "",
        f"**Grade {report.grade}** · score **{report.score}/100** · {len(report.tools)} tools · "
        f"{c['error']} errors, {c['warning']} warnings, {c['info']} info",
        "",
        f"Tool definitions cost about **{report.total_tokens:,} tokens** per turn "
        f"({report.token_method}).",
        "",
    ]
    if report.server_issues:
        lines += ["## Server-level issues", ""]
        for i in sorted_issues(report.server_issues):
            lines.append(f"- {SEV_ICON[i.severity]} **{i.rule}** {i.message}  \n  _Fix:_ {i.fix}")
        lines.append("")

    lines += ["## Tools", "", "| Tool | Score | Tokens | Errors | Warnings | Info |",
              "|---|---:|---:|---:|---:|---:|"]
    for t in sorted(report.tools, key=lambda t: (t.score, t.name)):
        tc = Counter(i.severity for i in t.issues)
        lines.append(f"| `{_md_escape(t.name)}` | {t.score} | {t.tokens:,} | "
                     f"{tc[Severity.ERROR]} | {tc[Severity.WARNING]} | {tc[Severity.INFO]} |")
    lines.append("")

    for t in sorted(report.tools, key=lambda t: (t.score, t.name)):
        if not t.issues:
            continue
        lines += [f"### `{t.name}` ({t.score}/100)", ""]
        for i in sorted_issues(t.issues):
            lines.append(f"- {SEV_ICON[i.severity]} **{i.rule}** {i.message}  \n  _Fix:_ {i.fix}")
        lines.append("")

    if report.fuzz_outcomes or report.fuzz_skipped:
        bad = [o for o in report.fuzz_outcomes if o.status in FUZZ_BAD]
        lines += ["## Fuzzing", "",
                  f"{len(report.fuzz_outcomes)} cases run, {len(bad)} problems found."]
        if report.fuzz_skipped:
            lines.append(f"Skipped (not marked read-only): {', '.join(f'`{s}`' for s in report.fuzz_skipped)}.")
        lines.append("")
    lines.append("_Generated by [MCP Doctor](https://scaleup-solutions.in/) from Scaleup Solutions._")
    return "\n".join(lines)


def print_terminal(report: Report, console=None) -> None:  # noqa: ANN001
    from rich.console import Console
    from rich.markup import escape as esc
    from rich.panel import Panel
    from rich.table import Table

    console = console or Console()
    c = report.counts()
    gstyle = GRADE_STYLE.get(report.grade, "bold")
    console.print(Panel.fit(
        f"[{gstyle}]Grade {report.grade}[/]  ·  score [bold]{report.score}[/]/100\n"
        f"{len(report.tools)} tools  ·  [red]{c['error']} errors[/]  ·  "
        f"[yellow]{c['warning']} warnings[/]  ·  [cyan]{c['info']} info[/]\n"
        f"~{report.total_tokens:,} tokens per turn [dim]({report.token_method})[/]",
        title=f"MCP Doctor · {esc(report.server)}", border_style=gstyle))

    table = Table(title="Tools (worst first)", show_lines=False)
    table.add_column("Tool")
    table.add_column("Score", justify="right")
    table.add_column("Tokens", justify="right")
    table.add_column("Issues")
    for t in sorted(report.tools, key=lambda t: (t.score, t.name)):
        tc = Counter(i.severity for i in t.issues)
        summary = " ".join(f"[{SEV_STYLE[s]}]{tc[s]} {s.value}[/]" for s in Severity if tc[s]) or "[green]clean[/]"
        style = "red" if t.score < 60 else "yellow" if t.score < 80 else "green"
        table.add_row(esc(t.name), f"[{style}]{t.score}[/]", f"{t.tokens:,}", summary)
    console.print(table)

    def show(issue: Issue) -> None:
        where = f"[bold]{esc(issue.tool)}[/] " if issue.tool else "[bold]server[/] "
        console.print(f"  [{SEV_STYLE[issue.severity]}]{issue.rule}[/] {where}{esc(issue.message)}",
                      highlight=False)
        console.print(f"       [dim]fix:[/] {esc(issue.fix)}", highlight=False)

    issues = sorted_issues(report.all_issues)
    if issues:
        console.print("\n[bold]Issues[/]")
        for i in issues:
            show(i)

    if report.fuzz_outcomes or report.fuzz_skipped:
        bad = [o for o in report.fuzz_outcomes if o.status in FUZZ_BAD]
        console.print(f"\n[bold]Fuzzing[/]: {len(report.fuzz_outcomes)} cases, "
                      f"[{'red' if bad else 'green'}]{len(bad)} problems[/]")
        if report.fuzz_skipped:
            console.print(f"  [dim]skipped (not marked read-only; use --allow-unsafe on a test "
                          f"instance): {esc(', '.join(report.fuzz_skipped))}[/]")
    top = top_rules(report)
    if top:
        console.print("\n[dim]Most common: " + ", ".join(f"{r} x{n}" for r, n in top) + "[/]")
